// Tests for the release guard: the CHANGELOG section, the store changelog and
// the version files a release is built from. Every case builds its own
// checkout in a temporary directory, so no fixture is committed and the real
// repository is only touched by the last test.
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

import { cargoPackageVersion, checkRelease, isMeaningful, sectionBody, versionCode } from "./release-guard.mjs";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..");

const SECTION = [
  "## [7.12.0] - 2026-11-07",
  "",
  "### Added",
  "",
  "- **Border styles arrive in N-up:** a frame honours `/BS /S`.",
  "",
].join("\n");

/** A checkout that passes, with one field replaceable per test. */
function checkout({ version = "7.12.0", changelog = SECTION, store = "Border styles arrive in N-up.\n", code } = {}) {
  const root = mkdtempSync(join(tmpdir(), "release-guard-"));
  writeFileSync(join(root, "package.json"), JSON.stringify({ name: "app", version }));
  mkdirSync(join(root, "src-tauri"), { recursive: true });
  writeFileSync(join(root, "src-tauri", "tauri.conf.json"), JSON.stringify({ version }));
  writeFileSync(join(root, "Cargo.toml"), `[workspace]\nmembers = []\n\n[workspace.package]\nversion = "${version}"\n`);
  const [major, minor, patch] = version.split(".").map(Number);
  const properties = [
    "// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.",
    `tauri.android.versionName=${version}`,
    `tauri.android.versionCode=${code ?? major * 1_000_000 + minor * 1_000 + patch}`,
    "",
  ].join("\n");
  mkdirSync(join(root, "src-tauri", "gen", "android", "app"), { recursive: true });
  writeFileSync(join(root, "src-tauri", "gen", "android", "app", "tauri.properties"), properties);
  if (changelog !== null) {
    writeFileSync(join(root, "CHANGELOG.md"), `# Changelog\n\n${changelog}`);
  }
  if (store !== null) {
    const directory = join(root, "fastlane", "metadata", "android", "en-US", "changelogs");
    mkdirSync(directory, { recursive: true });
    writeFileSync(join(directory, `${major * 1_000_000 + minor * 1_000 + patch}.txt`), store);
  }
  return root;
}

test("a version with its section and store changelog passes", () => {
  const result = checkRelease({ root: checkout() });
  assert.deepEqual(result.errors, []);
  assert.equal(result.version, "7.12.0");
  assert.equal(result.versionCode, 7012000);
});

test("a missing section replays the v7.12.0 incident", () => {
  // Both mistakes of that release are reported in one run, not one per attempt.
  const result = checkRelease({
    root: checkout({ changelog: "## [7.11.0] - 2026-11-06\n\n- old notes\n", store: null }),
  });
  assert.equal(result.errors.length, 2, result.errors.join("; "));
  assert.ok(
    result.errors.some((error) => error.includes("no '## [7.12.0]' section")),
    result.errors.join("; "),
  );
  assert.ok(
    result.errors.some((error) => error.includes("7012000.txt: file is missing")),
    result.errors.join("; "),
  );
});

test("a section with only a subheading is empty", () => {
  assert.equal(isMeaningful("\n### Added\n\n"), false);
  const result = checkRelease({ root: checkout({ changelog: "## [7.12.0]\n\n### Added\n\n## [7.11.0]\n\n- old\n" }) });
  assert.ok(
    result.errors.some((error) => error.includes("section is empty")),
    result.errors.join("; "),
  );
});

test("a section with only a comment or a placeholder is empty", () => {
  assert.equal(isMeaningful("<!-- to be written -->\n- TBD\n"), false);
  assert.equal(isMeaningful("- TODO\n…\n"), false);
  assert.equal(isMeaningful("- The window remembers the last page.\n"), true);
});

test("the section lookup does not accept a prefix of the version", () => {
  const changelog = "## [7.1.10]\n\n- later\n\n## [7.1.0]\n\n- mine\n";
  assert.ok(sectionBody(changelog, "7.1.0").includes("mine"));
  assert.equal(sectionBody("## [7.1.10]\n\n- later\n", "7.1.0"), null, "7.1.0 must not match 7.1.10");
  const result = checkRelease({ root: checkout({ version: "7.1.0", changelog: "## [7.1.10]\n\n- later\n" }) });
  assert.ok(
    result.errors.some((error) => error.includes("no '## [7.1.0]' section")),
    result.errors.join("; "),
  );
});

test("a section ends at the next release, not at a subheading", () => {
  const body = sectionBody(`${SECTION}\n## [7.11.0]\n\n- older notes\n`, "7.12.0");
  assert.ok(body.includes("Border styles"), body);
  assert.ok(!body.includes("older notes"), body);
  assert.ok(body.includes("### Added"), "subheadings stay inside the section");
});

test("a dated heading still matches, and [Unreleased] is not a release", () => {
  assert.ok(sectionBody(SECTION, "7.12.0").includes("Border styles"));
  assert.ok(sectionBody("## [7.12.0]\n\n- undated heading\n", "7.12.0").includes("undated heading"));
  assert.equal(sectionBody("## [Unreleased]\n\n- pending\n", "7.12.0"), null);
  const result = checkRelease({ root: checkout({ changelog: "## [Unreleased]\n\n- pending work\n" }) });
  assert.ok(
    result.errors.some((error) => error.includes("no '## [7.12.0]' section")),
    result.errors.join("; "),
  );
});

test("an empty or missing store changelog is refused", () => {
  const empty = checkRelease({ root: checkout({ store: "  \n" }) });
  assert.ok(
    empty.errors.some((error) => error.includes("file is empty")),
    empty.errors.join("; "),
  );
  const missing = checkRelease({ root: checkout({ store: null }) });
  assert.ok(
    missing.errors.some((error) => error.includes("file is missing")),
    missing.errors.join("; "),
  );
});

test("the version code is the store formula", () => {
  // The same numbers scripts/build-android.ps1 and fastlane-changelogs.mjs
  // produce; the pinned pairs make a silent change visible here.
  assert.equal(versionCode("7.12.0"), 7012000);
  assert.equal(versionCode("1.2.3"), 1002003);
  assert.equal(versionCode("10.0.0"), 10000000);
  assert.equal(versionCode("7.1000.0"), null, "a minor of 1000 would collide with the next major");
  assert.equal(versionCode("7.12.1000"), null);
  assert.equal(versionCode("7.12.0-rc1"), null);
  assert.equal(versionCode("v7.12.0"), null);
});

test("a Cargo manifest is read from [package] or the workspace", () => {
  assert.equal(cargoPackageVersion('[package]\nname = "x"\nversion = "1.2.3"\n'), "1.2.3");
  assert.equal(cargoPackageVersion('[workspace]\nmembers = []\n\n[workspace.package]\nversion = "9.8.7"\n'), "9.8.7");
  assert.equal(cargoPackageVersion('[package]\nname = "x"\nversion.workspace = true\n'), null);
  // `[workspace.package]` wins over a dependency's inline version table.
  assert.equal(
    cargoPackageVersion('[workspace.package]\nversion = "2.0.0"\n\n[dependencies]\nfoo = { version = "1.0.0" }\n'),
    "2.0.0",
  );
});

test("version files that disagree are all named", () => {
  const root = checkout();
  writeFileSync(join(root, "Cargo.toml"), '[workspace.package]\nversion = "7.13.0"\n');
  const result = checkRelease({ root });
  const error = result.errors.find((entry) => entry.startsWith("version files disagree"));
  assert.ok(error, result.errors.join("; "));
  assert.ok(error.includes("package.json=7.12.0"), error);
  assert.ok(error.includes("Cargo.toml=7.13.0"), error);
});

test("Android metadata has to agree with the version", () => {
  const root = checkout();
  writeFileSync(
    join(root, "src-tauri", "gen", "android", "app", "tauri.properties"),
    "tauri.android.versionName=7.11.0\ntauri.android.versionCode=7011000\n",
  );
  const result = checkRelease({ root });
  assert.ok(
    result.errors.some((error) => error.includes("versionName=7.11.0")),
    result.errors.join("; "),
  );
  assert.ok(
    result.errors.some((error) => error.includes("versionCode=7011000")),
    result.errors.join("; "),
  );
});

test("a tag has to match the version it will release", () => {
  assert.deepEqual(checkRelease({ root: checkout(), tag: "v7.12.0" }).errors, []);
  const wrong = checkRelease({ root: checkout(), tag: "v7.12.1" });
  assert.ok(
    wrong.errors.some((error) => error.includes("tag v7.12.1 does not match")),
    wrong.errors.join("; "),
  );
  // A dispatch on a branch has no tag to compare.
  assert.deepEqual(checkRelease({ root: checkout(), tag: "master" }).errors, []);
});

test("every problem is reported in one run", () => {
  const root = checkout({ changelog: "## [7.11.0]\n\n- old\n", store: null });
  writeFileSync(join(root, "Cargo.toml"), '[workspace.package]\nversion = "7.13.0"\n');
  const result = checkRelease({ root, tag: "v7.13.0" });
  assert.equal(result.errors.length, 4, result.errors.join("; "));
});

test("the repository at HEAD is releasable", () => {
  // Catches a fixture that drifted from the real layout: the guard has to pass
  // on the commit that ships it.
  const result = checkRelease({ root: REPO });
  assert.deepEqual(result.errors, []);
});
