const dictionaries: Record<string, Dict> = { en, tr };

export type Translate = (key: string, params?: Record<string, string | number>) => string;

export function makeTranslate(language: string): Translate {
  const dict = dictionaries[language] ?? dictionaries.en;
  return (key, params) => {
    let text = dict[key] ?? en[key] ?? key;
    if (params) {
      for (const [name, value] of Object.entries(params)) {
        text = text.replaceAll(`{${name}}`, String(value));
      }
    }
    return text;
  };
}

export function useT(): Translate {
  const language = useSettings((state) => state.settings.language);
  return useMemo(() => makeTranslate(language), [language]);
}
